const fs = require("fs");
const https = require("https");
const path = require("path");
const vm = require("vm");

const PROJECT_ROOT = path.resolve(__dirname, "..");
const SOURCE_REVISION = "7b1f881c2474bcb96fa8eacfbb8f63754c8cccef";
const SOURCE_URL = `https://huggingface.co/datasets/kknono668/toeic-vocab-tw/resolve/${SOURCE_REVISION}/data/toeic_vocabulary.json?download=true`;
const SET_ID = "toeic-vocab-tw";
const SET_OUTPUT_PATH = path.join(PROJECT_ROOT, "data", "vocabulary-sets", `${SET_ID}.json`);
const LOOKUP_OUTPUT_PATH = path.join(PROJECT_ROOT, "js", "g6-toeic-lookup.js");
const G6_VOCABULARY_PATH = path.join(PROJECT_ROOT, "js", "vocabulary.js");

async function main() {
  const sourceRows = JSON.parse((await downloadText(SOURCE_URL)).toString("utf8"));
  const entries = sourceRows.map(normalizeEntry);
  validateEntries(entries);

  const setData = {
    vocabularySetId: SET_ID,
    name: "TOEIC Vocabulary | 多益單字庫",
    source: {
      provider: "Hugging Face",
      dataset: "kknono668/toeic-vocab-tw",
      revision: SOURCE_REVISION,
      url: "https://huggingface.co/datasets/kknono668/toeic-vocab-tw"
    },
    totalCount: entries.length,
    entries
  };

  const g6Words = loadG6Words();
  const lookup = createG6Lookup(entries, g6Words);

  fs.mkdirSync(path.dirname(SET_OUTPUT_PATH), { recursive: true });
  fs.writeFileSync(SET_OUTPUT_PATH, `${JSON.stringify(setData)}\n`, "utf8");
  writeLookupFile(lookup);

  console.log(`Imported ${entries.length} TOEIC entries into ${path.relative(PROJECT_ROOT, SET_OUTPUT_PATH)}.`);
  console.log(`Matched ${lookup.matchedCount} of ${g6Words.length} G6 words into ${path.relative(PROJECT_ROOT, LOOKUP_OUTPUT_PATH)}.`);
}

function normalizeEntry(row, index) {
  const word = String(row.english_word || "").trim();
  return {
    vocabularySetId: SET_ID,
    wordId: `${SET_ID}:${String(index + 1).padStart(5, "0")}:${slugify(word)}`,
    word,
    partOfSpeech: Array.isArray(row.parts_of_speech) ? row.parts_of_speech : [],
    chineseMeaning: String(row.chinese_definition || "").trim(),
    categoryZh: String(row.category || "").trim(),
    starRating: row.star_rating,
    toeicScoreRange: String(row.toeic_score_range || "").trim(),
    wordForms: Array.isArray(row.word_forms) ? row.word_forms.map(function (form) {
      return {
        partOfSpeech: String(form.part_of_speech || "").trim(),
        forms: Array.isArray(form.forms) ? form.forms.map(String) : []
      };
    }) : [],
    examples: Array.isArray(row.examples) ? row.examples.map(function (example) {
      return {
        english: String(example.english || "").trim(),
        chinese: String(example.chinese || "").trim()
      };
    }) : [],
    examTips: Array.isArray(row.exam_tips) ? row.exam_tips.map(String) : []
  };
}

function createG6Lookup(entries, g6Words) {
  const byWord = new Map();
  entries.forEach(function (entry) {
    const key = normalizeWord(entry.word);
    if (!byWord.has(key)) {
      byWord.set(key, []);
    }
    byWord.get(key).push(entry);
  });

  const matchesByG6WordId = {};
  const unmatchedWordIds = [];
  g6Words.forEach(function (word) {
    const matches = byWord.get(normalizeWord(word.word)) || [];
    if (matches.length === 0) {
      unmatchedWordIds.push(word.wordId);
      return;
    }
    matchesByG6WordId[word.wordId] = matches;
  });

  return {
    vocabularySetId: SET_ID,
    sourceRevision: SOURCE_REVISION,
    totalEntries: entries.length,
    matchedCount: Object.keys(matchesByG6WordId).length,
    unmatchedWordIds,
    matchesByG6WordId
  };
}

function loadG6Words() {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(G6_VOCABULARY_PATH, "utf8"), sandbox, { filename: G6_VOCABULARY_PATH });
  if (!Array.isArray(sandbox.window.VOCABULARY_DATA)) {
    throw new Error("Unable to load js/vocabulary.js.");
  }
  return sandbox.window.VOCABULARY_DATA;
}

function validateEntries(entries) {
  if (entries.length === 0) {
    throw new Error("TOEIC source returned no entries.");
  }
  entries.forEach(function (entry) {
    if (!entry.word || !entry.chineseMeaning || !entry.categoryZh || !entry.toeicScoreRange) {
      throw new Error(`Incomplete TOEIC entry: ${entry.wordId}.`);
    }
  });
}

function writeLookupFile(lookup) {
  const output = [
    "// Generated by: scripts/import-toeic-vocab-tw.js",
    `// Source revision: ${SOURCE_REVISION}`,
    "// Contains only TOEIC entries matched to the built-in G6 vocabulary set.",
    `window.G6_TOEIC_LOOKUP_DATA = ${JSON.stringify(lookup)};`,
    ""
  ].join("\n");
  fs.writeFileSync(LOOKUP_OUTPUT_PATH, output, "utf8");
}

function normalizeWord(value) {
  return String(value || "").trim().toLowerCase();
}

function slugify(value) {
  return String(value || "word")
    .trim()
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "") || "word";
}

function downloadText(url) {
  return new Promise(function (resolve, reject) {
    https.get(url, { headers: { "User-Agent": "english-vocabulary-practice import script" } }, function (response) {
      if (response.statusCode >= 300 && response.statusCode < 400 && response.headers.location) {
        response.resume();
        resolve(downloadText(new URL(response.headers.location, url).toString()));
        return;
      }
      if (response.statusCode !== 200) {
        response.resume();
        reject(new Error(`Download failed with HTTP ${response.statusCode}.`));
        return;
      }
      const chunks = [];
      response.on("data", function (chunk) { chunks.push(chunk); });
      response.on("end", function () { resolve(Buffer.concat(chunks)); });
      response.on("error", reject);
    }).on("error", reject);
  });
}

main().catch(function (error) {
  console.error(error.message);
  process.exitCode = 1;
});
